import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { type BenchmarkModel, buildBenchmarkPool, fetchBenchmarks } from "../src/benchmarks.js";
import { loadEnv } from "../src/env.js";
import { loadOpenRouterCatalog } from "../src/openrouter.js";

const OUTPUT = fileURLToPath(new URL("../src/benchmarkSnapshot.ts", import.meta.url));

loadEnv();
const key = process.env.ARTIFICIAL_ANALYSIS_API_KEY?.trim();
if (!key) {
  console.error("Falta ARTIFICIAL_ANALYSIS_API_KEY (en .env o ~/.quillami/.env).");
  process.exit(1);
}

const [benchmarks, catalog] = await Promise.all([
  fetchBenchmarks(key),
  loadOpenRouterCatalog({ force: true }),
]);
if (!catalog) {
  console.error("No se pudo bajar el catálogo de OpenRouter.");
  process.exit(1);
}

const mapped = new Map<string, { model: BenchmarkModel; ids: string[] }>();
for (const candidate of buildBenchmarkPool(catalog, benchmarks)) {
  const model = benchmarks.find((entry) => entry.slug === candidate.slug)!;
  const entry = mapped.get(candidate.slug) ?? { model, ids: [] };
  entry.ids.push(candidate.model.id);
  mapped.set(candidate.slug, entry);
}

const entries = [...mapped.values()].sort(
  (a, b) => b.model.intelligence - a.model.intelligence || a.model.slug.localeCompare(b.model.slug),
);
const fetchedAt = new Date();
const lines = entries.map(({ model, ids }) => {
  const fields = `slug: ${JSON.stringify(model.slug)}, name: ${JSON.stringify(model.name)}, intelligence: ${model.intelligence}`;
  return `    { ${fields} }, // ${ids.sort().join(", ")}`;
});

writeFileSync(
  OUTPUT,
  `// Generated by \`npm run benchmarks:snapshot\`; do not edit by hand.
import type { BenchmarkModel } from "./benchmarks.js";

/**
 * Artificial Analysis intelligence index of the models that match the OpenRouter
 * catalog, used when the API can't be reached.
 */
export const BENCHMARK_SNAPSHOT: { fetchedAt: number; models: BenchmarkModel[] } = {
  fetchedAt: Date.parse(${JSON.stringify(fetchedAt.toISOString())}),
  models: [
${lines.join("\n")}
  ],
};
`,
  "utf8",
);

console.log(
  `${entries.length} modelos mapeados (de ${benchmarks.length} en Artificial Analysis y ${catalog.length} en OpenRouter) → src/benchmarkSnapshot.ts`,
);
